package Second;

public class switch_ {
public static void main(String[] args) {
	int value=10;
	switch(value)
	{
	case 1:
		System.out.println("23");
		break;
	case 2:
		System.out.println("32");
		break;
	case 3:
		System.out.println("33");
		break;
	default:
		System.out.println("45");			
	}	
	}
}

